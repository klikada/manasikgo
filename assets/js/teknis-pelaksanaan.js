const escapeHtmlTeknis = (value = "") =>
  String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

const renderTeknisStep = (step) => `
  <div class="step">
    <div class="num">${step.nomor}</div>
    <h4>${escapeHtmlTeknis(step.judul)}</h4>
    <p>${step.paragraf}</p>
    ${step.listIntro ? `<p class="step-intro">${escapeHtmlTeknis(step.listIntro)}</p>` : ""}
    ${
      step.list
        ? `<ul class="technical-list">${step.list
            .map((item) => `<li>${item}</li>`)
            .join("")}</ul>`
        : ""
    }
    ${
      step.infoBox
        ? `<div class="info-box">
      <b><i class="bi ${step.infoBox.icon}"></i> ${escapeHtmlTeknis(step.infoBox.title)}</b>
      ${step.infoBox.text}
    </div>`
        : ""
    }
    ${step.extraParagraf ? `<p class="step-intro">${step.extraParagraf}</p>` : ""}
  </div>`;

function renderTeknisPelaksanaanHaji() {
  const container = document.getElementById("teknisContent");
  if (!container) return;

  const stepsHtml = teknisPelaksanaanHajiData.map(renderTeknisStep).join("");
  container.innerHTML = `<div class="stepper technical-stepper">${stepsHtml}</div>`;
}




// Dipanggil langsung (bukan menunggu DOMContentLoaded) karena skrip ini
// dimuat tanpa "defer" persis sebelum </body>, sehingga #teknisContent

renderTeknisPelaksanaanHaji();

